/// Whether `dll` is a C runtime, whose functions are `cdecl`.
pub fn is_crt_dll(dll: &str) -> bool {
    let d = dll.to_ascii_lowercase();
    d.starts_with("msvcr")
        || d.starts_with("msvcp")
        || d.starts_with("ucrtbase")
        || d.starts_with("api-ms-win-crt")
        || d.starts_with("vcruntime")
        || d == "crtdll.dll"
}

