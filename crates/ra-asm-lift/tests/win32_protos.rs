//! The Windows API prototype table, generated from the SDK headers: `src/raise/prototypes/win32.rs`
//! holds, for every `__stdcall` function the headers declare, the kind of its result and of each
//! parameter. The ignored `regenerate_win32_prototypes` writes it: clang-cl preprocesses a file
//! that includes the headers (the SDK on the PATH's clang-cl is the one used), and the
//! declarations are read off the preprocessed text. The other tests check the table that is in.
//!
//!   `cargo test -p ra-asm-lift --test win32_protos -- --ignored regenerate`
//!
//! A kind is one letter: `i` an integer or pointer of the address width, `w` a 64-bit integer or
//! an 8-byte structure by value (two stack slots on x86), `d` a double, `f` a float, and for the
//! result `v` none. A variadic function, or one that takes a structure of another size by value,
//! is left out: the table says nothing rather than something wrong.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::{Path, PathBuf};
use std::process::Command;

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

const HEADERS: &[&str] = &[
    "winsock2.h",
    "ws2tcpip.h",
    "windows.h",
    "shellapi.h",
    "shlobj.h",
    "commctrl.h",
    "commdlg.h",
    "psapi.h",
    "tlhelp32.h",
    "wininet.h",
    "mmsystem.h",
    "dbghelp.h",
    "uxtheme.h",
    "dwmapi.h",
];

/// The 64-bit scalars and the 8-byte structures the API passes by value.
const WIDE: &[&str] = &[
    "LONGLONG",
    "ULONGLONG",
    "LONG64",
    "ULONG64",
    "DWORD64",
    "DWORDLONG",
    "INT64",
    "UINT64",
    "__int64",
    "LARGE_INTEGER",
    "ULARGE_INTEGER",
    "FILETIME",
    "LUID",
    "POINT",
    "POINTL",
    "SIZE",
    "SIZEL",
];

/// Structures of another size the API passes by value: a function that takes one is left out.
const BY_VALUE: &[&str] = &["GUID", "CLSID", "IID", "RECT", "RECTL", "TRIVERTEX", "DECIMAL", "VARIANT", "PROPVARIANT", "CY"];

#[test]
#[ignore = "a maintenance aid: regenerates src/raise/prototypes/win32.rs from the SDK headers with clang-cl"]
fn regenerate_win32_prototypes() {
    let dir = ra_asm_testing::Scratch::new("ra-asm-lift-tests", "win32-protos");
    let source = dir.join("headers.c");
    let mut includes = String::new();
    for header in HEADERS {
        let _ = writeln!(includes, "#include <{header}>");
    }
    std::fs::write(&source, format!("#define _WIN32_WINNT 0x0A00\n#define NTDDI_VERSION 0x0A000000\n{includes}")).unwrap();
    // The x86 target keeps `__stdcall` in the text; the types are the same on both.
    let out = Command::new("clang-cl").args(["--target=i686-pc-windows-msvc", "/nologo", "/E", "/W0"]).arg(&source).output().unwrap();
    assert!(out.status.success(), "clang-cl /E:\n{}", String::from_utf8_lossy(&out.stderr));
    let text = String::from_utf8_lossy(&out.stdout);
    let table = prototypes_of(&text);
    assert!(table.len() > 2000, "{} prototypes read, which is too few for windows.h", table.len());
    let mut file = String::new();
    file.push_str("//! The Windows API prototypes, from the SDK headers: the kind of the result and of each parameter of\n");
    file.push_str("//! every `__stdcall` function they declare (`i` integer or pointer, `w` 64-bit or an 8-byte structure,\n");
    file.push_str("//! `d` double, `f` float, `v` no result), sorted by name. Generated by the ignored test\n");
    file.push_str("//! `regenerate_win32_prototypes` in `tests/win32_protos.rs`; do not edit.\n\n");
    file.push_str("pub(super) static TABLE: &[(&str, &str)] = &[\n");
    for (name, kinds) in &table {
        let _ = writeln!(file, "    ({name:?}, {kinds:?}),");
    }
    file.push_str("];\n");
    let path = root().join("crates/ra-asm-lift/src/raise/prototypes/win32.rs");
    std::fs::write(&path, file).unwrap();
    eprintln!("{} prototypes -> {}", table.len(), path.display());
}

/// The prototypes declared in preprocessed C: name and kinds, by name.
fn prototypes_of(text: &str) -> BTreeMap<String, String> {
    let tokens = tokens_of(text);
    let mut table = BTreeMap::new();
    for statement in statements(&tokens) {
        let Some((name, kinds)) = prototype(statement) else { continue };
        table.entry(name).or_insert(kinds);
    }
    table
}

/// The tokens of preprocessed C: identifiers, numbers, string literals and single punctuation
/// characters, with the line markers left out.
fn tokens_of(text: &str) -> Vec<&str> {
    let mut tokens = Vec::new();
    for line in text.lines() {
        if line.trim_start().starts_with('#') {
            continue;
        }
        let bytes = line.as_bytes();
        let mut i = 0;
        while i < bytes.len() {
            let c = bytes[i];
            let start = i;
            if c.is_ascii_whitespace() {
                i += 1;
                continue;
            }
            if c.is_ascii_alphanumeric() || c == b'_' {
                while i < bytes.len() && (bytes[i].is_ascii_alphanumeric() || bytes[i] == b'_') {
                    i += 1;
                }
            } else if c == b'"' || c == b'\'' {
                i += 1;
                while i < bytes.len() && bytes[i] != c {
                    i += if bytes[i] == b'\\' { 2 } else { 1 };
                }
                i = (i + 1).min(bytes.len());
            } else if c == b'.' && bytes[i..].starts_with(b"...") {
                i += 3;
            } else {
                i += 1;
            }
            tokens.push(&line[start..i.min(bytes.len())]);
        }
    }
    tokens
}

/// The top-level statements: the tokens between one `;` or `}` and the next, with the insides of
/// braces left out (a structure body or a function body declares no API function).
fn statements<'a>(tokens: &'a [&'a str]) -> Vec<&'a [&'a str]> {
    let mut out = Vec::new();
    let mut depth = 0usize;
    let mut start = 0usize;
    for (i, &t) in tokens.iter().enumerate() {
        match t {
            "{" => {
                if depth == 0 {
                    out.push(&tokens[start..i]);
                }
                depth += 1;
            }
            "}" => {
                depth = depth.saturating_sub(1);
                if depth == 0 {
                    start = i + 1;
                }
            }
            ";" if depth == 0 => {
                out.push(&tokens[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    out
}

/// The name and kinds of the `__stdcall` function a statement declares, when it declares one.
fn prototype(statement: &[&str]) -> Option<(String, String)> {
    let at = statement.iter().position(|&t| t == "__stdcall")?;
    let name = *statement.get(at + 1)?;
    if *statement.get(at + 2)? != "("
        || !name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')
        || name.starts_with(|c: char| c.is_ascii_digit())
    {
        return None;
    }
    let prefix = &statement[..at];
    if prefix.iter().any(|&t| matches!(t, "typedef" | "static" | "inline" | "__inline" | "__forceinline")) {
        return None;
    }
    // The parameter list, to the parenthesis that closes it.
    let mut depth = 0usize;
    let mut end = None;
    for (i, &t) in statement.iter().enumerate().skip(at + 2) {
        match t {
            "(" => depth += 1,
            ")" => {
                depth -= 1;
                if depth == 0 {
                    end = Some(i);
                    break;
                }
            }
            _ => {}
        }
    }
    let params = &statement[at + 3..end?];
    let mut kinds = String::new();
    kinds.push(kind_of(prefix, true)?);
    if !(params.is_empty() || params == ["void"] || params == ["VOID"]) {
        let mut depth = 0usize;
        let mut start = 0usize;
        let mut groups = Vec::new();
        for (i, &t) in params.iter().enumerate() {
            match t {
                "(" | "[" => depth += 1,
                ")" | "]" => depth = depth.saturating_sub(1),
                "," if depth == 0 => {
                    groups.push(&params[start..i]);
                    start = i + 1;
                }
                _ => {}
            }
        }
        groups.push(&params[start..]);
        for group in groups {
            kinds.push(kind_of(group, false)?);
        }
    }
    Some((name.to_owned(), kinds))
}

/// The kind of a type, from its tokens: a pointer or an array is an integer of the address width,
/// a result of `void` is none, and `None` when the function should be left out.
fn kind_of(tokens: &[&str], result: bool) -> Option<char> {
    if tokens.contains(&"...") {
        return None;
    }
    if tokens.iter().any(|&t| t == "*" || t == "[" || t == "&") {
        return Some('i');
    }
    if tokens.iter().any(|&t| BY_VALUE.contains(&t)) {
        return None;
    }
    let names: Vec<&str> = tokens
        .iter()
        .copied()
        .filter(|t| !matches!(*t, "const" | "volatile" | "__declspec" | "(" | ")" | "dllimport" | "extern"))
        .collect();
    if names.contains(&"double") {
        return Some('d');
    }
    if names.contains(&"float") {
        return Some('f');
    }
    if names.iter().any(|&t| WIDE.contains(&t)) {
        return Some('w');
    }
    if result && names.last().is_some_and(|&t| t == "void" || t == "VOID") {
        return Some('v');
    }
    Some('i')
}

#[test]
fn declarations_read_as_prototypes() {
    let text = "\
# 1 \"winbase.h\"
__declspec(dllimport) BOOL __stdcall WriteFile(HANDLE hFile, LPCVOID lpBuffer, DWORD n, LPDWORD written, LPOVERLAPPED o);
__declspec(dllimport) BOOL __stdcall SetFilePointerEx(HANDLE hFile, LARGE_INTEGER liDistanceToMove, PLARGE_INTEGER lpNewFilePointer, DWORD dwMoveMethod);
__declspec(dllimport) ULONGLONG __stdcall GetTickCount64(void);
__declspec(dllimport) VOID __stdcall ExitProcess(UINT uExitCode);
typedef BOOL (__stdcall *PHANDLER_ROUTINE)(DWORD CtrlType);
__declspec(dllimport) int __cdecl wsprintfA(LPSTR, LPCSTR, ...);
__declspec(dllimport) HWND __stdcall ChildWindowFromPoint(HWND hWndParent, POINT Point);
__declspec(dllimport) HRESULT __stdcall CoCreateGuid(GUID *pguid);
__declspec(dllimport) HRESULT __stdcall StringFromCLSID(CLSID rclsid, LPOLESTR *lplpsz);
struct S { int (__stdcall *inner)(int); };
static __inline int __stdcall Helper(int x) { return x; }
__declspec(dllimport) double __stdcall GetDoubleValue(float f, unsigned __int64 q);
";
    let table = prototypes_of(text);
    assert_eq!(table.get("WriteFile").map(String::as_str), Some("iiiiii"));
    assert_eq!(table.get("SetFilePointerEx").map(String::as_str), Some("iiwii"));
    assert_eq!(table.get("GetTickCount64").map(String::as_str), Some("w"));
    assert_eq!(table.get("ExitProcess").map(String::as_str), Some("vi"));
    assert_eq!(table.get("ChildWindowFromPoint").map(String::as_str), Some("iiw"));
    assert_eq!(table.get("CoCreateGuid").map(String::as_str), Some("ii"));
    assert_eq!(table.get("GetDoubleValue").map(String::as_str), Some("dfw"));
    for absent in ["PHANDLER_ROUTINE", "wsprintfA", "StringFromCLSID", "inner", "Helper"] {
        assert!(!table.contains_key(absent), "{absent} is in the table");
    }
}

/// The table that is in: sorted, and right about the functions the hand table knows.
#[test]
fn the_generated_table_names_the_common_api() {
    use ra_asm_lift::raise::abi::Kind;
    use ra_asm_lift::raise::prototypes::{arity, typed, win32};
    let (returns, params) = win32("WriteFile").expect("WriteFile is in the table");
    assert_eq!((returns, params.len()), (Some(Kind::Int), 5));
    assert_eq!(win32("GetTickCount64").map(|(r, p)| (r, p.len())), Some((Some(Kind::Wide), 0)));
    assert_eq!(win32("SetFilePointerEx").map(|(_, p)| p), Some(vec![Kind::Int, Kind::Wide, Kind::Int, Kind::Int]));
    assert_eq!(win32("ExitProcess").map(|(r, p)| (r, p.len())), Some((None, 1)));
    // The table reaches past the hand one, and agrees with it where both know a function.
    assert_eq!(arity("GetDiskFreeSpaceExA"), Some(4));
    assert_eq!(arity("CreateWindowExW"), Some(12));
    assert_eq!(arity("MultiByteToWideChar"), Some(6));
    assert!(typed("ChildWindowFromPoint").is_some_and(|t| t.params == [Kind::Int, Kind::Wide]));
    assert!(win32("wsprintfA").is_none(), "a variadic function is in the table");
    assert!(win32("printf").is_none());
}
